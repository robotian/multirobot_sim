def _fmt_time(t):
    return t.astimezone().strftime("%Y-%m-%d %H:%M:%S") if t else ""


def _print_render(r):
    if r["source"] == "offline":
        print(f"[fleetcfg] {r['why']}; .env kept as it is" if not r.get("changed") else
              f"[fleetcfg] {r['why']}; .env made from the defaults", file=sys.stderr)
    for w in r.get("warnings", []):
        print(f"[fleetcfg] warning: {w}", file=sys.stderr)
    for e in r.get("errors", []):
        print(f"[fleetcfg] error: {e}", file=sys.stderr)


def cmd_show(a):
    v = view()
    if v["source"] == "offline":
        print(f"(database unreachable: {v['why']}; showing .env)")
    print(f"profile: {v['profile']}")
    for section in v["sections"]:
        print(f"\n[{section}]")
        for s in v["catalog"]:
            if s["section"] != section:
                continue
            val = v["settings"].get(s["key"])
            if val is None and s["advanced"] and not a.all:
                continue
            print(f"  {s['key']:26} {val if val is not None else s['default']!s:24} "
                  f"{'' if val is not None else '(default)'}")
    other = sorted(k for k in v["settings"] if k not in cat.BY_KEY)
    if other:
        print("\n[Not in the catalog]")
        for k in other:
            print(f"  {k:26} {v['settings'][k]}")
    print(f"\n[Robot slots]  NUM_ROBOTS={v['num_robots']}")
    for s in v["slots"]:
        if s["stored"] or s["slot"] < v["num_robots"]:
            pose = f"({s['x']:g}, {s['y']:g}, {s['yaw']:g}°)" if s["x"] is not None else "default pose"
            print(f"  {s['slot']}  {s['model']:12} {s['ns']:12} {pose:28} "
                  f"{'' if s['slot'] < v['num_robots'] else '(not started)'}")
    for e in v["errors"]:
        print(f"error: {e}")
    for w in v["warnings"]:
        print(f"warning: {w}")
    if not a.all:
        print("\n(advanced settings at their default hidden: --all)")


