def profile_import(data, name=None, actor=None):
    """A profile_export() dict as a new profile (name: data's, else NAME)."""
    name = name or data.get("profile")
    settings = {k: str(v) for k, v in (data.get("settings") or {}).items()}
    for k, v in settings.items():
        if not re.fullmatch(r"[A-Z][A-Z0-9_]*", k) or cat.is_derived(k) or cat.check_value(k, v):
            raise ValueError(f"{k}={v}: not a valid setting")
    slots = {}
    for s in data.get("slots") or []:
        i = int(s["slot"])
        if not 0 <= i < cat.MAX_SLOTS or not re.fullmatch(r"[a-z0-9]+(_[0-9]+)?", s.get("model", "")):
            raise ValueError(f"bad slot {s}")
        has_pose = all(s.get(k) is not None for k in ("x", "y", "yaw"))
        x, y, yaw = _pose(s if has_pose else None)
        slots[i] = {"model": s["model"], "x": x, "y": y, "yaw": yaw}
    with DB(actor) as db:
        _create_profile(db, name, settings, slots, data.get("notes") or "imported")
    return name


def import_env(path, profile=None, actor=None):
    """An old-style .env into a profile: a new one, or replacing the settings and slots of an existing one."""
    settings, slots, notes = import_env_vals(parse_env(Path(path).read_text()))
    with DB(actor) as db:
        active(db)
        pid = db.val("SELECT id FROM profile WHERE name = ?", (profile,)) if profile else None
        if pid is None:
            _create_profile(db, profile or Path(path).name, settings, slots, f"imported from {path}")
        else:
            for k in [r[0] for r in db.all("SELECT key FROM setting_value WHERE profile_id = ?", (pid,))]:
                if k not in settings:
                    _delete(db, "setting_value", {"profile_id": pid, "key": k})
            for i in [r[0] for r in db.all("SELECT slot FROM robot_slot WHERE profile_id = ?", (pid,))]:
                if i not in slots:
                    _delete(db, "robot_slot", {"profile_id": pid, "slot": i})
            for k, v in settings.items():
                _put(db, "setting_value", {"profile_id": pid, "key": k, "value": v})
            for i, s in slots.items():
                _put_slot(db, pid, i, s["model"], s["x"], s["y"], s["yaw"])
        render(actor, db)
    return notes


