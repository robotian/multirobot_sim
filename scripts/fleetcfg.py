def _db_file():
    v = os.environ.get("FLEET_CONFIG_DB")
    if not v:
        return ROOT / "fleet_config.sqlite"
    if "/" in v:
        return Path(v)
    return ROOT / (v if v.endswith((".sqlite", ".db")) else v + ".sqlite")  # a bare name: a file next to .env


DB_FILE = _db_file()


class Unavailable(RuntimeError):
    """The database file can't be opened or set up (permissions, a failed migration)."""


def default_actor():
    return f"{getpass.getuser()}@{socket.gethostname()}"


def now_iso():
    return datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%dT%H:%M:%S.%f")[:-3] + "Z"


def to_iso(t):
    """A datetime (from PostgreSQL) as the database's UTC ISO text."""
    if t is None or isinstance(t, str):
        return t
    return t.astimezone(datetime.timezone.utc).strftime("%Y-%m-%dT%H:%M:%S.%f")[:-3] + "Z"


def from_iso(s):
    return datetime.datetime.fromisoformat(s.replace("Z", "+00:00")) if s else None


# ---------------------------------------------------------------- .env files

def parse_env(text):
    """KEY=VALUE lines as docker compose reads them (last one wins; surrounding quotes removed)."""
    out = {}
    for line in text.splitlines():
        line = line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        k, v = line.split("=", 1)
        k, v = k.strip().removeprefix("export ").strip(), v.strip()
        if len(v) >= 2 and v[0] == v[-1] and v[0] in "\"'":
            v = v[1:-1]
        out[k] = v
    return out


def read_env_file(path=ENV_FILE):
    try:
        return parse_env(path.read_text())
    except OSError:
        return {}


def env_is_generated(path=ENV_FILE):
    try:
        with open(path) as f:
            return f.readline().startswith(HEADER)
    except OSError:
        return False


def write_if_changed(path, text):
    try:
        if path.read_text() == text:
            return False
    except OSError:
        pass
    # a unique temporary file: the web UI renders from several threads at once
    fd, tmp = tempfile.mkstemp(dir=path.parent, prefix=f".{path.name.lstrip('.')}.", suffix=".tmp")
    with os.fdopen(fd, "w") as f:
        f.write(text)
    os.chmod(tmp, 0o644)
    os.replace(tmp, path)  # atomic: compose never reads half a file
    return True


def git(*args):
    p = subprocess.run(["git", "-C", str(ROOT), *args], capture_output=True, text=True)
    return p.stdout if p.returncode == 0 else None


def from_git_history(rel):
    """A file's last committed content (before it was untracked), for the first-use import on a fresh checkout."""
    commit = (git("log", "-1", "--format=%H", "--", rel) or "").strip()
    if not commit:
        return None, None
    for rev in (commit, commit + "^"):  # the commit that untracked it has it only in its parent
        text = git("show", f"{rev}:{rel}")
        if text is not None:
            return text, f"git {rev[:9]}"
    return None, None


# ---------------------------------------------------------------- database

def _statements(sql):
    """A migration file's statements, one by one (executescript would commit the open transaction)."""
    out, cur = [], ""
    for line in sql.splitlines(keepends=True):
        cur += line
        if sqlite3.complete_statement(cur):
            out.append(cur)
            cur = ""
    if any(l.strip() and not l.strip().startswith("--") for l in cur.splitlines()):
        out.append(cur)  # an unterminated last statement: let SQLite report it
    return out


def _migrate(conn):
    """Apply scripts/fleet_config_migrations/*.sql not yet in schema_migrations, each in one transaction."""
    conn.execute("CREATE TABLE IF NOT EXISTS schema_migrations (version text PRIMARY KEY, "
                 "applied_at text NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ', 'now')))")
    done = {r[0] for r in conn.execute("SELECT version FROM schema_migrations")}
    for f in sorted(MIGRATIONS.glob("*.sql")):
        if f.stem in done:
            continue
        conn.execute("BEGIN IMMEDIATE")
        try:
            if not conn.execute("SELECT 1 FROM schema_migrations WHERE version = ?", (f.stem,)).fetchone():
                for statement in _statements(f.read_text()):
                    conn.execute(statement)
                conn.execute("INSERT INTO schema_migrations (version) VALUES (?)", (f.stem,))
            conn.execute("COMMIT")
        except sqlite3.Error as e:
            conn.execute("ROLLBACK")
            raise Unavailable(f"{DB_FILE}: migration {f.name} failed ({e})") from None


CONSTRAINTS = {  # scripts/fleet_config_migrations/: what a violation means
    "profile.name": "there is a profile with that name already",
    "length(name)": "a profile name is letters, digits, spaces, '.', '_' and '-' (up to 63)",
    "id GLOB": "a real robot id looks like j100_0921",
    "model GLOB": "a model id looks like a300 or j100_0921",
}

# Primary keys and columns of the logged tables (change_log rows hold whole rows as JSON).
TABLE_KEYS = {"profile": ("id",), "active_profile": ("only_row",), "setting_value": ("profile_id", "key"),
              "robot_slot": ("profile_id", "slot"), "real_robot": ("id",)}
COLUMNS = {"profile": ("id", "name", "notes", "created_at"), "active_profile": ("only_row", "profile_id"),
           "setting_value": ("profile_id", "key", "value"),
           "robot_slot": ("profile_id", "slot", "model", "x", "y", "yaw_deg"),
           "real_robot": ("id", "host", "ssh_user", "cutter")}
BULK_TABLES = ("setting_value", "robot_slot")  # not logged row by row while a whole profile is created/deleted


class DB:
    """One connection, one write transaction: `with DB() as db:` commits at the end, rolls back on an exception.
    BEGIN IMMEDIATE serialises writers (the web UI's threads and the command line); WAL keeps readers going."""

    def __init__(self, actor=None):
        self.actor = actor or default_actor()
        self.bulk = False
        try:
            self.conn = sqlite3.connect(str(DB_FILE), timeout=15, isolation_level=None)
            self.conn.execute("PRAGMA foreign_keys = ON")
            if self.conn.execute("PRAGMA journal_mode").fetchone()[0] != "wal":
                self.conn.execute("PRAGMA journal_mode = WAL")
            _migrate(self.conn)
            self.conn.execute("BEGIN IMMEDIATE")
        except sqlite3.Error as e:
            raise Unavailable(f"settings database {DB_FILE}: {e}") from None
        self.cur = self.conn.cursor()

    def q(self, sql, args=()):
        self.cur.execute(sql, args)
        return self.cur

    def all(self, sql, args=()):
        return self.q(sql, args).fetchall()

    def one(self, sql, args=()):
        return self.q(sql, args).fetchone()

    def val(self, sql, args=()):
        row = self.one(sql, args)
        return row[0] if row else None

    def dicts(self, sql, args=()):
        cur = self.q(sql, args)
        cols = [d[0] for d in cur.description]
        return [dict(zip(cols, r)) for r in cur.fetchall()]

    def __enter__(self):
        return self

    def __exit__(self, exc_type, exc, tb):
        try:
            self.conn.execute("COMMIT" if exc_type is None else "ROLLBACK")
        finally:
            self.conn.close()
        if isinstance(exc, sqlite3.IntegrityError):  # a constraint (name taken, bad model id...): the caller's mistake
            msg = str(exc)
            for constraint, text in CONSTRAINTS.items():
                if constraint in msg:
                    msg = text
            raise ValueError(msg) from exc


def _row(db, table, key):
    keys = TABLE_KEYS[table]
    rows = db.dicts(f"SELECT {', '.join(COLUMNS[table])} FROM {table} WHERE "
                    + " AND ".join(f"{k} = ?" for k in keys), [key[k] for k in keys])
    return rows[0] if rows else None


def _log(db, table, op, old, new):
    if (db.bulk and table in BULK_TABLES) or old == new:
        return
    db.q("INSERT INTO change_log (actor, tbl, op, old_row, new_row) VALUES (?, ?, ?, ?, ?)",
         (db.actor, table, op, None if old is None else json.dumps(old), None if new is None else json.dumps(new)))


def _put(db, table, row):
    """Insert or update one row by its primary key, and log the change."""
    keys = TABLE_KEYS[table]
    old = _row(db, table, row)
    cols = [c for c in COLUMNS[table] if c in row]
    db.q(f"INSERT INTO {table} ({', '.join(cols)}) VALUES ({', '.join('?' * len(cols))}) "
         f"ON CONFLICT ({', '.join(keys)}) DO UPDATE SET "
         + ", ".join(f"{c} = excluded.{c}" for c in cols if c not in keys), [row[c] for c in cols])
    new = _row(db, table, row)
    _log(db, table, "INSERT" if old is None else "UPDATE", old, new)
    return new


def _delete(db, table, key):
    old = _row(db, table, key)
    if old is None:
        return False
    keys = TABLE_KEYS[table]
    db.q(f"DELETE FROM {table} WHERE " + " AND ".join(f"{k} = ?" for k in keys), [key[k] for k in keys])
    _log(db, table, "DELETE", old, None)
    return True


def _note(db, text):
    """A change log line that is not a row change (an import)."""
    db.q("INSERT INTO change_log (actor, tbl, op, new_row) VALUES (?, 'import', 'IMPORT', ?)",
         (db.actor, json.dumps({"source": text})))


# ---------------------------------------------------------------- the PostgreSQL fleet_config, once

def running_pg():
    """PGPORT/PGUSER of the running base station container ({} if it isn't running or docker isn't there)."""
    try:
        p = subprocess.run(["docker", "inspect", "-f", "{{if .State.Running}}{{range .Config.Env}}{{println .}}"
                            "{{end}}{{end}}", BASESTATION], capture_output=True, text=True, timeout=10)
    except (OSError, subprocess.TimeoutExpired):
        return {}
    return dict(line.split("=", 1) for line in p.stdout.splitlines() if line.startswith(("PGPORT=", "PGUSER=")))


def _import_postgres(db):
    """Copy the PostgreSQL fleet_config a running base station held (2026-10-09/10) whole: profiles, settings,
    slots, real robots, the change log and runs, ids kept. None if there is none to reach (no psycopg, the base
    station not running here, no such database, or it has no profile)."""
    if os.environ.get("FLEET_NO_PG_IMPORT"):
        return None
    try:
        import psycopg as drv
    except ImportError:
        try:
            import psycopg2 as drv
        except ImportError:
            return None
    pg = running_pg()
    if not pg:
        return None
    env, secrets = read_env_file(), read_env_file(ROOT / "db.env")
    try:
        pc = drv.connect(host="127.0.0.1", port=int(pg.get("PGPORT") or env.get("BASESTATION_PG_PORT") or 5433),
                         user=pg.get("PGUSER") or "admin", dbname="fleet_config", connect_timeout=3,
                         password=secrets.get("PGPASSWORD") or os.environ.get("PGPASSWORD", ""))
    except drv.Error:
        return None
    try:
        cur = pc.cursor()

        def rows(sql):
            cur.execute(sql)
            cols = [d[0] for d in cur.description]
            return [dict(zip(cols, r)) for r in cur.fetchall()]
        try:
            profs = rows("SELECT id, name, notes, created_at FROM profile ORDER BY id")
        except drv.Error:
            return None
        if not profs:
            return None
        for p in profs:
            db.q("INSERT INTO profile (id, name, notes, created_at) VALUES (?, ?, ?, ?)",
                 (p["id"], p["name"], p["notes"], to_iso(p["created_at"])))
        for r in rows("SELECT profile_id, key, value FROM setting_value"):
            db.q("INSERT INTO setting_value (profile_id, key, value) VALUES (?, ?, ?)",
                 (r["profile_id"], r["key"], r["value"]))
        for r in rows("SELECT profile_id, slot, model, x, y, yaw_deg FROM robot_slot"):
            db.q("INSERT INTO robot_slot (profile_id, slot, model, x, y, yaw_deg) VALUES (?, ?, ?, ?, ?, ?)",
                 (r["profile_id"], r["slot"], r["model"], r["x"], r["y"], r["yaw_deg"]))
        for r in rows("SELECT profile_id FROM active_profile"):
            db.q("INSERT INTO active_profile (only_row, profile_id) VALUES (1, ?)", (r["profile_id"],))
        for r in rows("SELECT id, host, ssh_user, cutter FROM real_robot"):
            db.q("INSERT INTO real_robot (id, host, ssh_user, cutter) VALUES (?, ?, ?, ?)",
                 (r["id"], r["host"], r["ssh_user"], int(bool(r["cutter"]))))
        log = rows("SELECT id, at, actor, tbl, op, old_row, new_row FROM change_log ORDER BY id")
        for r in log:
            db.q("INSERT INTO change_log (id, at, actor, tbl, op, old_row, new_row) VALUES (?, ?, ?, ?, ?, ?, ?)",
                 (r["id"], to_iso(r["at"]), r["actor"], r["tbl"], r["op"],
                  None if r["old_row"] is None else json.dumps(r["old_row"]),
                  None if r["new_row"] is None else json.dumps(r["new_row"])))
        runs_ = rows("SELECT id, started_at, finished_at, actor, command, profile, git_commit, env, exit_code FROM run")
        for r in runs_:
            db.q("INSERT INTO run (id, started_at, finished_at, actor, command, profile, git_commit, env, exit_code) "
                 "VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)",
                 (r["id"], to_iso(r["started_at"]), to_iso(r["finished_at"]), r["actor"], r["command"],
                  r["profile"], r["git_commit"], json.dumps(r["env"]), r["exit_code"]))
        if not db.val("SELECT 1 FROM active_profile"):
            db.q("INSERT INTO active_profile (only_row, profile_id) VALUES (1, ?)", (profs[0]["id"],))
        return (f"the base station's PostgreSQL fleet_config ({len(profs)} profile(s), {len(log)} change(s), "
                f"{len(runs_)} run(s))")
    finally:
        pc.close()


# ---------------------------------------------------------------- the active profile

def slot_ns(model, slot):
    """Container name / ROS namespace: a real robot's own id, else <model>_<slot %04d> (docker-compose.yml)."""
    return model if "_" in model else f"{model}_{slot:04d}"


def import_env_vals(vals):
    """An old-style .env's variables -> (settings, slots, notes). Derived variables are dropped (render makes them)."""
    settings, slots, notes = {}, {}, []
    for k, v in vals.items():
        m = re.fullmatch(r"ROBOT_(MODEL|POSE)_(\d+)", k)
        if m:
            i = int(m[2])
            if i >= cat.MAX_SLOTS:
                notes.append(f"{k}: no slot {i} (0-{cat.MAX_SLOTS - 1})")
                continue
            s = slots.setdefault(i, {"model": GENERIC_SLOT_MODEL, "x": None, "y": None, "yaw": None})
            if m[1] == "MODEL":
                if not re.fullmatch(r"[a-z0-9]+(_[0-9]+)?", v):
                    notes.append(f"{k}={v}: not a model id, slot {i} left {s['model']}")
                else:
                    s["model"] = v
            else:
                try:
                    x, y, yaw = (float(p) for p in v.split(","))
                    s.update(x=x, y=y, yaw=yaw)
                except ValueError:
                    notes.append(f"{k}={v}: not x,y,yaw")
            continue
        if cat.is_derived(k):
            continue
        if not re.fullmatch(r"[A-Z][A-Z0-9_]*", k) or cat.is_reserved(k):
            notes.append(f"{k}: not a setting name, skipped")
            continue
        err = cat.check_value(k, v)
        if err:
            notes.append(f"{k}={v}: skipped, must be {err}")
            continue
        settings[k] = v
    return settings, slots, notes


def _create_profile(db, name, settings, slots, notes=""):
    db.bulk = True  # the change log gets the profile, not each of its settings and slots
    pid = db.val("INSERT INTO profile (name, notes) VALUES (?, ?) RETURNING id", (name, notes))
    _log(db, "profile", "INSERT", None, _row(db, "profile", {"id": pid}))
    for k, v in settings.items():
        _put(db, "setting_value", {"profile_id": pid, "key": k, "value": v})
    for i, s in slots.items():
        _put(db, "robot_slot", {"profile_id": pid, "slot": i, "model": s["model"], "x": s.get("x"),
                                "y": s.get("y"), "yaw_deg": s.get("yaw")})
    return pid


def _first_use(db):
    """No profile yet: import the base station's old PostgreSQL fleet_config if it can be reached, else this
    checkout's .env (hand-written from before the database, or generated: the newest state either way), else
    the last one committed to git, and real_robots.json."""
    source = _import_postgres(db)
    if source:
        _note(db, source)
        print(f"[fleetcfg] first use of {DB_FILE.name}: imported {source}", file=sys.stderr)
        return
    notes = []
    if ENV_FILE.exists():
        text, source = ENV_FILE.read_text(), "the .env file"
    else:
        text, source = from_git_history(".env")
    if text is None:
        settings, slots, source = {}, {}, "defaults"
    else:
        settings, slots, notes = import_env_vals(parse_env(text))
    pid = _create_profile(db, "default", settings, slots, f"imported from {source}")
    _put(db, "active_profile", {"only_row": 1, "profile_id": pid})
    if not db.val("SELECT count(*) FROM real_robot"):
        try:
            real = json.loads(REAL_FILE.read_text())
        except (OSError, ValueError):
            text, _ = from_git_history(str(REAL_FILE.relative_to(ROOT)))
            real = json.loads(text) if text else {}
        for rid, c in real.items():
            if re.fullmatch(r"[a-z0-9]+_[0-9]+", rid) and isinstance(c, dict):
                _put(db, "real_robot", {"id": rid, "host": c.get("host") or f"cpr-{rid.replace('_', '-')}.local",
                                        "ssh_user": c.get("user") or "robot", "cutter": int(bool(c.get("cutter")))})
    _note(db, source)
    for n in notes:
        print(f"[fleetcfg] import: {n}", file=sys.stderr)
    print(f"[fleetcfg] first use of {DB_FILE.name}: profile 'default' imported from {source}", file=sys.stderr)


def active(db):
    """(id, name) of the active profile; the first use of the database imports one (BEGIN IMMEDIATE: one at a time)."""
    row = db.one("SELECT p.id, p.name FROM active_profile a JOIN profile p ON p.id = a.profile_id")
    if row:
        return row
    first = db.one("SELECT id, name FROM profile ORDER BY id LIMIT 1")
    if first:
        _put(db, "active_profile", {"only_row": 1, "profile_id": first[0]})
        return first
    _first_use(db)
    return db.one("SELECT p.id, p.name FROM active_profile a JOIN profile p ON p.id = a.profile_id")


def profile_id(db, name):
    pid = db.val("SELECT id FROM profile WHERE name = ?", (name,))
    if pid is None:
        raise ValueError(f"no profile {name!r}")
    return pid


def load(db, pid=None):
    """{profile, settings: {key: value}, slots: {i: {model, x, y, yaw}}} of a profile (the active one by default)."""
    if pid is None:
        pid, name = active(db)
    else:
        name = db.val("SELECT name FROM profile WHERE id = ?", (pid,))
    settings = dict(db.all("SELECT key, value FROM setting_value WHERE profile_id = ? ORDER BY key", (pid,)))
    slots = {r[0]: {"model": r[1], "x": r[2], "y": r[3], "yaw": r[4]} for r in
             db.all("SELECT slot, model, x, y, yaw_deg FROM robot_slot WHERE profile_id = ? ORDER BY slot", (pid,))}
    return {"profile_id": pid, "profile": name, "settings": settings, "slots": slots}


def default_cfg():
    return {"profile_id": None, "profile": None, "settings": {}, "slots": {}}


def effective(cfg, key):
    v = cfg["settings"].get(key)
    if v is None and key in cat.BY_KEY:
        v = cat.BY_KEY[key]["default"]
    return v


def num_robots(cfg):
    try:
        return int(effective(cfg, "NUM_ROBOTS") or 0)
    except ValueError:
        return 0


def linked_real_robots(cfg, real):
    """{id: endpoint} of the real robots the base station's zenoh router dials (BASESTATION_ZENOH_CONNECT has
    tcp/<their host>:7447). The router routes between everything it dials, the sim's zenoh-router included, so
    such a robot shares one ROS graph with the sim, whether it is on now or powers on later."""
    if (effective(cfg, "BASESTATION_RMW") or effective(cfg, "FLEET_RMW")) != "rmw_zenoh_cpp":
        return {}
    endpoints = set((effective(cfg, "BASESTATION_ZENOH_CONNECT") or "").split())
    return {r["id"]: f"tcp/{r['host']}:7447" for r in real or () if f"tcp/{r['host']}:7447" in endpoints}


def problems(cfg, real=None):
    """(errors, warnings): errors stop render (compose would fail or the sim reject the spawn). real: the
    real_robot rows (the sim/real clash check needs their hosts)."""
    errors, warnings = [], []
    n = num_robots(cfg)
    if not 0 <= n <= cat.MAX_SLOTS:
        errors.append(f"NUM_ROBOTS={n}: 0-{cat.MAX_SLOTS}")
        n = 0
    seen = {}
    linked = linked_real_robots(cfg, real)
    for i in range(n):
        model = cfg["slots"].get(i, {}).get("model", GENERIC_SLOT_MODEL)
        ns = slot_ns(model, i)
        if ns in seen:
            errors.append(f"slots {seen[ns]} and {i} are both {ns}: one real robot can only be in one slot")
        seen[ns] = i
        if model in linked:
            # the sim robot would publish the real one's topics (cmd_vel, arm goals) into the graph the real one
            # joins through the base station, and the real robot would answer the sim robot's tools
            errors.append(f"slot {i} is the real robot {model}, which the base station's router dials "
                          f"({linked[model]}): the sim robot would share its ROS names, and commands meant for "
                          f"one could reach the other. Unlink {model} (Base station card, or "
                          f"BASESTATION_ZENOH_CONNECT), or give slot {i} another model")
        if "_" in model and not (ROOT / "robot_data" / model / "robot.yaml").exists():
            warnings.append(f"slot {i} ({model}): no robot_data/{model}/robot.yaml, its container exits at once")
        if not (ROOT / "sim/assets" / model / f"{model}.urdf").exists():
            warnings.append(f"slot {i}: no sim model sim/assets/{model}/ (scripts/gen_urdf.sh)")
    for k, v in cfg["settings"].items():
        if cat.is_reserved(k):
            errors.append(f"{k}: docker compose's own variable, not a setting (scripts/fleetcfg.py unset {k})")
            continue
        err = cat.check_value(k, v)
        if err:
            errors.append(f"{k}={v}: must be {err}")
    return errors, warnings


def _env_value(v):
    return f'"{v}"' if re.search(r"[\s#]", v) else v


def render_text(cfg, source):
    """The .env text for a profile: its settings (unset ones are left to compose's defaults) and the slots.
    No timestamp: the same settings give the same text, so .env is only rewritten when they change."""
    lines = [f"{HEADER} from {source} -- do not edit: changes are overwritten.",
             "# Change settings in the web UI (tools/sim_ui, Configuration) or with scripts/fleetcfg.py set KEY=VALUE.",
             f"# Profile: {cfg['profile'] or '(none: database unusable, defaults)'}."]
    settings = dict(cfg["settings"])
    settings.setdefault("NUM_ROBOTS", cat.BY_KEY["NUM_ROBOTS"]["default"])
    for section in cat.SECTIONS:
        keys = [s["key"] for s in cat.SETTINGS if s["section"] == section and s["key"] in settings]
        if keys:
            lines += ["", f"# {section}"] + [f"{k}={_env_value(settings[k])}" for k in keys]
    other = sorted(k for k in settings if k not in cat.BY_KEY)
    if other:
        lines += ["", "# Not in scripts/fleet_settings.py"] + [f"{k}={_env_value(settings[k])}" for k in other]
    n = num_robots(cfg)
    lines += ["", "# Robot slots: compose profile n<NUM_ROBOTS> starts slots 0..N-1; container name, hostname",
              "# and namespace follow each slot's model (see docker-compose.yml)", f"COMPOSE_PROFILES=n{n}"]
    for i in range(cat.MAX_SLOTS):
        s = cfg["slots"].get(i)
        model = s["model"] if s else GENERIC_SLOT_MODEL
        if s:
            lines.append(f"ROBOT_MODEL_{i}={model}")
            if s.get("x") is not None:
                lines.append(f"ROBOT_POSE_{i}={s['x']:g},{s['y']:g},{s['yaw']:g}")
        if "_" in model:
            lines.append(f"ROBOT_SUFFIX_{i}=")
        lines.append(f"ROBOT_HOSTNAME_{i}=cpr-{slot_ns(model, i).replace('_', '-')}")
    return "\n".join(lines) + "\n"


def _real_rows(db):
    return [dict(r, cutter=bool(r["cutter"]))
            for r in db.dicts("SELECT id, host, ssh_user AS user, cutter FROM real_robot ORDER BY id")]


def _write_real_file(rows):
    data = {r["id"]: {"host": r["host"], **({"user": r["user"]} if r["user"] != "robot" else {}),
                      "cutter": r["cutter"]} for r in rows}
    write_if_changed(REAL_FILE, json.dumps(data, indent=2) + "\n")


def render(actor=None, db=None):
    """Write .env (and the real-robot list) from the active profile. Returns {source, profile, changed, errors,
    warnings, why}: source "database", or "offline" (the database file can't be opened: .env kept, or made from
    the defaults if there is none). Errors: nothing written."""
    try:
        if db is None:
            with DB(actor) as own:
                return render(actor, own)
        cfg = load(db)
        real = _real_rows(db)
    except Unavailable as e:
        r = {"source": "offline", "why": str(e), "profile": None, "errors": [], "warnings": [], "changed": False}
        if not ENV_FILE.exists():
            r["changed"] = write_if_changed(ENV_FILE, render_text(default_cfg(), "the defaults (no database)"))
        return r
    errors, warnings = problems(cfg, real)
    r = {"source": "database", "why": "", "profile": cfg["profile"], "errors": errors, "warnings": warnings,
         "changed": False}
    if not errors:
        r["changed"] = write_if_changed(ENV_FILE, render_text(cfg, DB_FILE.name))
        _write_real_file(real)
    return r


