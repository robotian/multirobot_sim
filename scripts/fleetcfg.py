# ---------------------------------------------------------------- history and runs

def _slot_text(r):
    if not r:
        return "(none)"
    pose = f" at ({r['x']:g}, {r['y']:g}, {r['yaw_deg']:g}°)" if r.get("x") is not None else ""
    return r["model"] + pose


def _real_text(r):
    return f"{r['ssh_user']}@{r['host']}{', cutter' if r['cutter'] else ''}" if r else "(none)"


def describe(e, names):
    o, n = e["old_row"], e["new_row"]
    r = n or o
    t = e["tbl"]
    where = f"[{names.get(r.get('profile_id'), '#' + str(r.get('profile_id')))}] " if "profile_id" in r and t != "active_profile" else ""
    if t == "setting_value":
        return f"{where}{r['key']}: {o['value'] if o else '(default)'} -> {n['value'] if n else '(default)'}"
    if t == "robot_slot":
        return f"{where}slot {r['slot']}: {_slot_text(o)} -> {_slot_text(n)}"
    if t == "real_robot":
        return f"real robot {r['id']}: {_real_text(o)} -> {_real_text(n)}"
    if t == "active_profile":
        return (f"active profile: {names.get(o['profile_id'], '#' + str(o['profile_id'])) if o else '(none)'} -> "
                f"{names.get(n['profile_id'], '#' + str(n['profile_id'])) if n else '(none)'}")
    if t == "profile":
        if e["op"] == "INSERT":
            return f"profile {n['name']} created"
        if e["op"] == "DELETE":
            return f"profile {o['name']} deleted"
        return (f"profile {o['name']} renamed {n['name']}" if o["name"] != n["name"]
                else f"profile {n['name']}: notes changed")
    return f"{t} {e['op']}"


def history(limit=50, actor=None):
    with DB(actor) as db:
        rows = db.dicts("SELECT id, at, actor, tbl, op, old_row, new_row FROM change_log ORDER BY id DESC LIMIT %s",
                        (limit,))
        names = dict(db.all("SELECT id, name FROM profile"))
    for r in rows:
        r["text"] = describe(r, names)
        r["revertible"] = r["tbl"] in ("setting_value", "robot_slot", "real_robot", "active_profile")
    return rows


PKEYS = {"setting_value": ("profile_id", "key"), "robot_slot": ("profile_id", "slot"), "real_robot": ("id",)}
COLUMNS = {"setting_value": ("profile_id", "key", "value"),
           "robot_slot": ("profile_id", "slot", "model", "x", "y", "yaw_deg"),
           "real_robot": ("id", "host", "ssh_user", "cutter")}


def revert(entry_id, actor=None):
    """Put back what change ENTRY_ID changed (as a new change, itself in the log)."""
    with DB(actor) as db:
        e = db.dicts("SELECT tbl, op, old_row, new_row FROM change_log WHERE id = %s", (entry_id,))
        if not e:
            raise ValueError(f"no change {entry_id}")
        t, o, n = e[0]["tbl"], e[0]["old_row"], e[0]["new_row"]
        if t == "active_profile":
            if not o or not db.val("SELECT 1 FROM profile WHERE id = %s", (o["profile_id"],)):
                raise ValueError("that profile no longer exists")
            db.q("UPDATE active_profile SET profile_id = %s", (o["profile_id"],))
        elif t in PKEYS:
            r = o or n
            if "profile_id" in r and not db.val("SELECT 1 FROM profile WHERE id = %s", (r["profile_id"],)):
                raise ValueError("its profile no longer exists")
            keys = PKEYS[t]
            if o is None:  # it was added: remove it
                db.q(f"DELETE FROM {t} WHERE " + " AND ".join(f"{k} = %s" for k in keys), [n[k] for k in keys])
            else:
                cols = COLUMNS[t]
                db.q(f"INSERT INTO {t} ({', '.join(cols)}) VALUES ({', '.join(['%s'] * len(cols))}) "
                     f"ON CONFLICT ({', '.join(keys)}) DO UPDATE SET "
                     + ", ".join(f"{c} = EXCLUDED.{c}" for c in cols if c not in keys), [o[c] for c in cols])
        else:
            raise ValueError(f"a {t} change can't be reverted")
        r = render(actor, db)
        if r["errors"]:
            raise ValueError("; ".join(r["errors"]))
        return r


def run_begin(command, actor=None):
    """Record a scripts/fleet.sh run with the variables it runs with; its id, or None without a database."""
    commit = (git("rev-parse", "--short", "HEAD") or "").strip()
    if commit and (git("status", "--porcelain", "--untracked-files=no") or "").strip():
        commit += "-dirty"
    try:
        with DB(actor) as db:
            _, name = active(db)
            return db.val("INSERT INTO run (actor, command, profile, git_commit, env) VALUES (%s, %s, %s, %s, "
                          "%s::jsonb) RETURNING id", (actor or default_actor(), command, name, commit,
                                                      json.dumps(read_env_file())))
    except Unavailable:
        return None


def run_end(run_id, code, actor=None):
    try:
        with DB(actor) as db:
            db.q("UPDATE run SET finished_at = now(), exit_code = %s WHERE id = %s", (code, run_id))
    except Unavailable:
        pass


def runs(limit=30, actor=None):
    with DB(actor) as db:
        return db.dicts("SELECT id, started_at, finished_at, actor, command, profile, git_commit, exit_code, env "
                        "FROM run ORDER BY id DESC LIMIT %s", (limit,))


