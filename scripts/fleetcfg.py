# ---------------------------------------------------------------- check: catalog vs. compose

def check():
    text = (ROOT / "docker-compose.yml").read_text() + (ROOT / "basestation.compose.yml").read_text()
    used = {}
    for m in re.finditer(r"\$\{([A-Z][A-Z0-9_]*)(:?-)?([^}$]*)", text):
        used.setdefault(m[1], set()).add(m[3] if m[2] else None)
    bad = 0
    for s in cat.SETTINGS:
        k = s["key"]
        if k in cat.NOT_IN_COMPOSE:
            continue
        if k not in used:
            print(f"{k}: in the catalog but not in docker-compose.yml / basestation.compose.yml")
            bad += 1
            continue
        defaults = used[k] - {None}
        if k == "BASESTATION_RMW":  # ${BASESTATION_RMW:-${FLEET_RMW...}}: empty = FLEET_RMW
            continue
        if defaults and defaults != {s["default"]}:
            print(f"{k}: catalog default {s['default']!r}, compose {sorted(defaults)}")
            bad += 1
    for k in sorted(used):
        if k not in cat.BY_KEY and not cat.is_derived(k) and k not in ("DISPLAY", "VAR"):
            print(f"{k}: used by compose, not in scripts/fleet_settings.py")
            bad += 1
    print("catalog matches compose" if not bad else f"{bad} problem(s)")
    return 1 if bad else 0


# ---------------------------------------------------------------- command line

def _fmt_time(t):
    t = from_iso(t) if isinstance(t, str) else t
    return t.astimezone().strftime("%Y-%m-%d %H:%M:%S") if t else ""


def _print_render(r):
    if r["source"] == "offline":
        print(f"[fleetcfg] {r['why']}; .env kept as it is" if not r.get("changed") else
              f"[fleetcfg] {r['why']}; .env made from the defaults", file=sys.stderr)
    for w in r.get("warnings", []):
        print(f"[fleetcfg] warning: {w}", file=sys.stderr)
    for e in r.get("errors", []):
        print(f"[fleetcfg] error: {e}", file=sys.stderr)


def cmd_show(a):
    v = view()
    if v["source"] == "offline":
        print(f"(settings database unusable: {v['why']}; showing .env)")
    print(f"profile: {v['profile']}   ({v['db']})")
    for section in v["sections"]:
        print(f"\n[{section}]")
        for s in v["catalog"]:
            if s["section"] != section:
                continue
            val = v["settings"].get(s["key"])
            if val is None and s["advanced"] and not a.all:
                continue
            print(f"  {s['key']:26} {val if val is not None else s['default']!s:24} "
                  f"{'' if val is not None else '(default)'}")
    other = sorted(k for k in v["settings"] if k not in cat.BY_KEY)
    if other:
        print("\n[Not in the catalog]")
        for k in other:
            print(f"  {k:26} {v['settings'][k]}")
    print(f"\n[Robot slots]  NUM_ROBOTS={v['num_robots']}")
    for s in v["slots"]:
        if s["stored"] or s["slot"] < v["num_robots"]:
            pose = f"({s['x']:g}, {s['y']:g}, {s['yaw']:g}°)" if s["x"] is not None else "default pose"
            print(f"  {s['slot']}  {s['model']:12} {s['ns']:12} {pose:28} "
                  f"{'' if s['slot'] < v['num_robots'] else '(not started)'}")
    for e in v["errors"]:
        print(f"error: {e}")
    for w in v["warnings"]:
        print(f"warning: {w}")
    if not a.all:
        print("\n(advanced settings at their default hidden: --all)")


def cmd_get(a):
    try:
        with DB() as db:
            cfg = load(db)
    except Unavailable:
        cfg = dict(default_cfg(), settings=read_env_file())
    v = effective(cfg, a.key)
    if v is None:
        return 1
    print(v)


def cmd_set(a):
    updates = {}
    for kv in a.pairs:
        if "=" not in kv:
            raise ValueError(f"{kv}: KEY=VALUE")
        k, v = kv.split("=", 1)
        updates[k.strip()] = v
    _print_render(set_settings(updates))


def cmd_unset(a):
    _print_render(set_settings({k: None for k in a.keys}))


def cmd_robots(a):
    _print_render(set_settings({"NUM_ROBOTS": str(a.n)}))


def cmd_slot(a):
    pose = None
    if a.pose:
        try:
            x, y, yaw = (float(v) for v in a.pose.split(","))
        except ValueError:
            raise ValueError("--pose X,Y,YAW (m, m, degrees)") from None
        pose = {"x": x, "y": y, "yaw": yaw}
    _print_render(set_slot(a.slot, a.model, pose, a.no_pose, a.remove))


def cmd_render(a):
    r = render()
    _print_render(r)
    if not a.quiet and r["source"] == "database":
        print(f"[fleetcfg] .env {'written' if r['changed'] else 'unchanged'} (profile {r['profile']})", file=sys.stderr)
    return 1 if r["errors"] else 0


def cmd_profile(a):
    if a.op == "list":
        with DB() as db:
            active(db)
            for p in profiles(db):
                print(f"{'*' if p['active'] else ' '} {p['name']:24} {p['num_robots'] or '-':>3} robots  "
                      f"{p['settings']:>3} settings  {p['notes']}")
    elif a.op == "use":
        _print_render(profile_use(a.args[0]))
    elif a.op == "new":
        profile_new(a.args[0], a.source)
    elif a.op == "rename":
        profile_rename(a.args[0], a.args[1])
    elif a.op == "delete":
        profile_delete(a.args[0])
    elif a.op == "notes":
        profile_notes(a.args[0], " ".join(a.args[1:]))
    elif a.op == "export":
        print(json.dumps(profile_export(a.args[0] if a.args else None), indent=2))
    elif a.op == "import":
        print(f"imported as profile {profile_import(json.loads(Path(a.args[0]).read_text()), a.name)}")


def cmd_history(a):
    for r in reversed(history(a.n)):
        print(f"{r['id']:>6}  {_fmt_time(r['at'])}  {r['actor']:24}  {r['text']}")


def cmd_revert(a):
    _print_render(revert(a.id))


def cmd_runs(a):
    for r in reversed(runs(a.n)):
        code = "running" if r["exit_code"] is None and not r["finished_at"] else f"exit {r['exit_code']}"
        print(f"{r['id']:>5}  {_fmt_time(r['started_at'])}  {code:8}  {r['command']:24} profile {r['profile']}, "
              f"{r['env'].get('NUM_ROBOTS', '?')} robot(s), git {r['git_commit']}  ({r['actor']})")


def cmd_real(a):
    if a.op == "list":
        for rid, c in real_robots().items():
            print(f"{rid:12} {c['user']}@{c['host']}{'  cutter' if c['cutter'] else ''}")
    elif a.op == "set":
        cur = real_robots().get(a.id, {})
        real_save(a.id, a.host or cur.get("host") or f"cpr-{a.id.replace('_', '-')}.local",
                  a.user or cur.get("user") or "robot", cur.get("cutter", False) if a.cutter is None else a.cutter)
    elif a.op == "remove":
        real_remove(a.id)


def cmd_import_env(a):
    for n in import_env(a.file, a.profile):
        print(f"note: {n}")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    p = sub.add_parser("show")
    p.add_argument("--all", action="store_true", help="also advanced settings left at their default")
    p.set_defaults(fn=cmd_show)
    p = sub.add_parser("get")
    p.add_argument("key")
    p.set_defaults(fn=cmd_get)
    p = sub.add_parser("set")
    p.add_argument("pairs", nargs="+", metavar="KEY=VALUE")
    p.set_defaults(fn=cmd_set)
    p = sub.add_parser("unset")
    p.add_argument("keys", nargs="+")
    p.set_defaults(fn=cmd_unset)
    p = sub.add_parser("robots")
    p.add_argument("n", type=int)
    p.set_defaults(fn=cmd_robots)
    p = sub.add_parser("slot")
    p.add_argument("slot", type=int)
    p.add_argument("model", nargs="?")
    p.add_argument("--pose", help="X,Y,YAW: metres, metres, degrees")
    p.add_argument("--no-pose", action="store_true", help="the sim's default layout")
    p.add_argument("--remove", action="store_true", help="forget the slot (a300 if it is started)")
    p.set_defaults(fn=cmd_slot)
    p = sub.add_parser("render")
    p.add_argument("--quiet", action="store_true")
    p.set_defaults(fn=cmd_render)
    p = sub.add_parser("profile")
    p.add_argument("op", choices=["list", "use", "new", "rename", "delete", "notes", "export", "import"])
    p.add_argument("args", nargs="*")
    p.add_argument("--from", dest="source", help="new: copy this profile (default: the active one)")
    p.add_argument("--name", help="import: the new profile's name")
    p.set_defaults(fn=cmd_profile)
    p = sub.add_parser("history")
    p.add_argument("-n", type=int, default=30)
    p.set_defaults(fn=cmd_history)
    p = sub.add_parser("revert")
    p.add_argument("id", type=int)
    p.set_defaults(fn=cmd_revert)
    p = sub.add_parser("runs")
    p.add_argument("-n", type=int, default=20)
    p.set_defaults(fn=cmd_runs)
    p = sub.add_parser("real")
    p.add_argument("op", choices=["list", "set", "remove"])
    p.add_argument("id", nargs="?")
    p.add_argument("--host")
    p.add_argument("--user")
    p.add_argument("--cutter", action="store_true", default=None)
    p.add_argument("--no-cutter", dest="cutter", action="store_false")
    p.set_defaults(fn=cmd_real)
    p = sub.add_parser("import-env")
    p.add_argument("file")
    p.add_argument("--profile")
    p.set_defaults(fn=cmd_import_env)
    p = sub.add_parser("check")
    p.set_defaults(fn=lambda a: check())
    # used by scripts/fleet.sh
    p = sub.add_parser("run-begin")
    p.add_argument("command")
    p.set_defaults(fn=lambda a: print(run_begin(a.command) or ""))
    p = sub.add_parser("run-end")
    p.add_argument("id", type=int)
    p.add_argument("code", type=int)
    p.set_defaults(fn=lambda a: run_end(a.id, a.code))
    a = ap.parse_args()
    if a.cmd == "real" and a.op != "list" and not a.id:
        ap.error("real set/remove need an ID")
    try:
        sys.exit(a.fn(a) or 0)
    except (ValueError, Unavailable) as e:
        print(f"fleetcfg: {e}", file=sys.stderr)
        sys.exit(1)


if __name__ == "__main__":
    main()
