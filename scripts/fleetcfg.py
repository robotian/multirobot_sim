class Unavailable(RuntimeError):
    """The database can't be reached (or has no tables yet)."""


def default_actor():
    return f"{getpass.getuser()}@{socket.gethostname()}"


# ---------------------------------------------------------------- .env files

def parse_env(text):
    """KEY=VALUE lines as docker compose reads them (last one wins; surrounding quotes removed)."""
    out = {}
    for line in text.splitlines():
        line = line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        k, v = line.split("=", 1)
        k, v = k.strip().removeprefix("export ").strip(), v.strip()
        if len(v) >= 2 and v[0] == v[-1] and v[0] in "\"'":
            v = v[1:-1]
        out[k] = v
    return out


def read_env_file(path=ENV_FILE):
    try:
        return parse_env(path.read_text())
    except OSError:
        return {}


def env_is_generated(path=ENV_FILE):
    try:
        with open(path) as f:
            return f.readline().startswith(HEADER)
    except OSError:
        return False


def write_if_changed(path, text):
    try:
        if path.read_text() == text:
            return False
    except OSError:
        pass
    # a unique temporary file: the web UI renders from several threads at once
    fd, tmp = tempfile.mkstemp(dir=path.parent, prefix=f".{path.name.lstrip('.')}.", suffix=".tmp")
    with os.fdopen(fd, "w") as f:
        f.write(text)
    os.chmod(tmp, 0o644)
    os.replace(tmp, path)  # atomic: compose never reads half a file
    return True


def git(*args):
    p = subprocess.run(["git", "-C", str(ROOT), *args], capture_output=True, text=True)
    return p.stdout if p.returncode == 0 else None


def from_git_history(rel):
    """A file's last committed content (before it was untracked), for the first-use import on a fresh checkout."""
    commit = (git("log", "-1", "--format=%H", "--", rel) or "").strip()
    if not commit:
        return None, None
    for rev in (commit, commit + "^"):  # the commit that untracked it has it only in its parent
        text = git("show", f"{rev}:{rel}")
        if text is not None:
            return text, f"git {rev[:9]}"
    return None, None


