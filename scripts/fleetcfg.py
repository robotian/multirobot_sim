_down = {"until": 0.0, "why": ""}


def _driver():
    try:
        import psycopg
        return psycopg
    except ImportError:
        pass
    try:
        import psycopg2
        return psycopg2
    except ImportError:
        raise Unavailable("no PostgreSQL driver for python3: pip install 'psycopg[binary]' "
                          "(or sudo apt install python3-psycopg2)") from None


def conn_params():
    env = read_env_file()
    secrets = read_env_file(ROOT / "db.env")
    return {"host": os.environ.get("FLEET_DB_HOST", "127.0.0.1"),
            "port": int(os.environ.get("FLEET_DB_PORT") or env.get("BASESTATION_PG_PORT") or 5433),
            "user": os.environ.get("FLEET_DB_USER") or env.get("BASESTATION_PG_USER") or "admin",
            "password": secrets.get("PGPASSWORD") or os.environ.get("PGPASSWORD", ""),
            "dbname": DB_NAME, "connect_timeout": 3}


def basestation_running():
    p = subprocess.run(["docker", "inspect", "-f", "{{.State.Running}}", BASESTATION], capture_output=True, text=True)
    return p.stdout.strip() == "true"


CONSTRAINTS = {  # basestation/config_migrations/: what a violation means
    "profile_name_key": "there is a profile with that name already",
    "profile_name_check": "a profile name is letters, digits, spaces, '.', '_' and '-' (up to 63)",
    "real_robot_id_check": "a real robot id looks like j100_0921",
    "robot_slot_model_check": "a model id looks like a300 or j100_0921",
}


class DB:
    """One connection, one transaction: `with DB() as db:` commits at the end, rolls back on an exception."""

    def __init__(self, actor=None, auto_init=True):
        if time.time() < _down["until"]:
            raise Unavailable(_down["why"])
        drv = _driver()
        params = conn_params()
        try:
            self.conn = drv.connect(**params)
        except drv.Error as e:
            msg = str(e).strip().splitlines()[0] if str(e).strip() else type(e).__name__
            # a base station from before fleet_config existed: create it in place (no restart needed)
            if auto_init and "does not exist" in msg and basestation_running() and init(quiet=True) == 0:
                self.__init__(actor, auto_init=False)
                return
            why = (f"no settings database at {params['host']}:{params['port']}/{DB_NAME} ({msg}); is the base "
                   "station running? docker compose -f basestation.compose.yml up -d")
            _down.update(until=time.time() + OFFLINE_RETRY_S, why=why)
            raise Unavailable(why) from None
        self.drv = drv
        self.cur = self.conn.cursor()
        if self.val("SELECT to_regclass('profile') IS NULL"):
            self.conn.close()
            if auto_init and basestation_running() and init(quiet=True) == 0:
                self.__init__(actor, auto_init=False)
                return
            raise Unavailable(f"{DB_NAME} has no tables: scripts/fleetcfg.py init")
        self.q("SELECT set_config('fleet.actor', %s, false)", (actor or default_actor(),))

    def q(self, sql, args=()):
        self.cur.execute(sql, args)
        return self.cur

    def all(self, sql, args=()):
        return self.q(sql, args).fetchall()

    def one(self, sql, args=()):
        return self.q(sql, args).fetchone()

    def val(self, sql, args=()):
        row = self.one(sql, args)
        return row[0] if row else None

    def dicts(self, sql, args=()):
        cur = self.q(sql, args)
        cols = [d[0] for d in cur.description]
        return [dict(zip(cols, r)) for r in cur.fetchall()]

    def __enter__(self):
        return self

    def __exit__(self, exc_type, exc, tb):
        try:
            if exc_type is None:
                self.conn.commit()
            else:
                self.conn.rollback()
        finally:
            self.conn.close()
        if isinstance(exc, self.drv.Error):  # a constraint (name taken, bad model id...): the caller's mistake
            msg = str(exc).strip().splitlines()[0]
            for constraint, text in CONSTRAINTS.items():
                if constraint in msg:
                    msg = text
            raise ValueError(msg) from exc


def init(quiet=False):
    """Create fleet_config in the running base station container and apply basestation/config_migrations/ with
    its own migrate.sh (copied in: a container from before them doesn't mount the folder)."""
    def run(argv, **kw):
        p = subprocess.run(argv, capture_output=True, text=True, **kw)
        if p.returncode != 0 and not quiet:
            print(p.stdout + p.stderr, file=sys.stderr, end="")
        return p
    if not basestation_running():
        if not quiet:
            print("the base station is not running: docker compose -f basestation.compose.yml up -d", file=sys.stderr)
        return 1
    exists = run(["docker", "exec", BASESTATION, "psql", "-tAq", "-d", "postgres", "-c",
                  f"SELECT 1 FROM pg_database WHERE datname = '{DB_NAME}'"])
    if exists.returncode != 0:
        return 1
    if not exists.stdout.strip():
        if run(["docker", "exec", BASESTATION, "psql", "-q", "-d", "postgres", "-c",
                f'CREATE DATABASE "{DB_NAME}"']).returncode != 0:
            return 1
    # tar through docker exec, not docker cp: that fails on the container's /tmp/.docker.xauth bind mount
    tmp = "/var/tmp/fleetcfg_migrations"
    src = ROOT / "basestation/config_migrations"
    tar = subprocess.run(["tar", "-C", str(src), "-c", "."], capture_output=True)
    if run(["docker", "exec", "-i", BASESTATION, "sh", "-c", f'rm -rf {tmp} && mkdir -p {tmp} && tar -C {tmp} -x'],
           input=tar.stdout.decode("latin-1"), encoding="latin-1").returncode != 0:
        return 1
    p = run(["docker", "exec", "-e", f"PGDATABASE={DB_NAME}", BASESTATION, "/basestation-migrate.sh", tmp])
    if not quiet and p.returncode == 0:
        print(p.stdout, end="")
    return p.returncode


# ---------------------------------------------------------------- the active profile

def slot_ns(model, slot):
    """Container name / ROS namespace: a real robot's own id, else <model>_<slot %04d> (docker-compose.yml)."""
    return model if "_" in model else f"{model}_{slot:04d}"


def import_env_vals(vals):
    """An old-style .env's variables -> (settings, slots, notes). Derived variables are dropped (render makes them)."""
    settings, slots, notes = {}, {}, []
    for k, v in vals.items():
        m = re.fullmatch(r"ROBOT_(MODEL|POSE)_(\d+)", k)
        if m:
            i = int(m[2])
            if i >= cat.MAX_SLOTS:
                notes.append(f"{k}: no slot {i} (0-{cat.MAX_SLOTS - 1})")
                continue
            s = slots.setdefault(i, {"model": GENERIC_SLOT_MODEL, "x": None, "y": None, "yaw": None})
            if m[1] == "MODEL":
                if not re.fullmatch(r"[a-z0-9]+(_[0-9]+)?", v):
                    notes.append(f"{k}={v}: not a model id, slot {i} left {s['model']}")
                else:
                    s["model"] = v
            else:
                try:
                    x, y, yaw = (float(p) for p in v.split(","))
                    s.update(x=x, y=y, yaw=yaw)
                except ValueError:
                    notes.append(f"{k}={v}: not x,y,yaw")
            continue
        if cat.is_derived(k):
            continue
        if not re.fullmatch(r"[A-Z][A-Z0-9_]*", k):
            notes.append(f"{k}: not a setting name, skipped")
            continue
        err = cat.check_value(k, v)
        if err:
            notes.append(f"{k}={v}: skipped, must be {err}")
            continue
        settings[k] = v
    return settings, slots, notes


def _bulk(db):
    """The change log records only the profile row for the rest of this transaction (fleet.bulk, log_change)."""
    db.q("SELECT set_config('fleet.bulk', 'on', true)")


def _create_profile(db, name, settings, slots, notes=""):
    _bulk(db)
    pid = db.val("INSERT INTO profile (name, notes) VALUES (%s, %s) RETURNING id", (name, notes))
    for k, v in settings.items():
        db.q("INSERT INTO setting_value (profile_id, key, value) VALUES (%s, %s, %s)", (pid, k, v))
    for i, s in slots.items():
        db.q("INSERT INTO robot_slot (profile_id, slot, model, x, y, yaw_deg) VALUES (%s, %s, %s, %s, %s, %s)",
             (pid, i, s["model"], s.get("x"), s.get("y"), s.get("yaw")))
    return pid


def _first_use(db):
    """No profile yet: import this checkout's .env (hand-written from before the database, or generated by an
    earlier one: the newest state either way), else the last one committed to git, and real_robots.json."""
    notes = []
    if ENV_FILE.exists():
        text, source = ENV_FILE.read_text(), "the .env file"
    else:
        text, source = from_git_history(".env")
    if text is None:
        settings, slots, source = {}, {}, "defaults"
    else:
        settings, slots, notes = import_env_vals(parse_env(text))
    pid = _create_profile(db, "default", settings, slots, f"imported from {source}")
    db.q("INSERT INTO active_profile (profile_id) VALUES (%s)", (pid,))
    if not db.val("SELECT count(*) FROM real_robot"):
        try:
            real = json.loads(REAL_FILE.read_text())
        except (OSError, ValueError):
            text, _ = from_git_history(str(REAL_FILE.relative_to(ROOT)))
            real = json.loads(text) if text else {}
        for rid, c in real.items():
            if re.fullmatch(r"[a-z0-9]+_[0-9]+", rid) and isinstance(c, dict):
                db.q("INSERT INTO real_robot (id, host, ssh_user, cutter) VALUES (%s, %s, %s, %s)",
                     (rid, c.get("host") or f"cpr-{rid.replace('_', '-')}.local", c.get("user") or "robot",
                      bool(c.get("cutter"))))
    for n in notes:
        print(f"[fleetcfg] import: {n}", file=sys.stderr)
    print(f"[fleetcfg] first use: profile 'default' imported from {source}", file=sys.stderr)


def active(db):
    """(id, name) of the active profile; the first use of the database imports one."""
    row = db.one("SELECT p.id, p.name FROM active_profile a JOIN profile p ON p.id = a.profile_id")
    if row:
        return row
    db.q("SELECT pg_advisory_xact_lock(%s)", (FIRST_USE_LOCK,))
    row = db.one("SELECT p.id, p.name FROM active_profile a JOIN profile p ON p.id = a.profile_id")
    if row:
        return row
    first = db.one("SELECT id, name FROM profile ORDER BY id LIMIT 1")
    if first:
        db.q("INSERT INTO active_profile (profile_id) VALUES (%s)", (first[0],))
        return first
    _first_use(db)
    return db.one("SELECT p.id, p.name FROM active_profile a JOIN profile p ON p.id = a.profile_id")


def profile_id(db, name):
    pid = db.val("SELECT id FROM profile WHERE name = %s", (name,))
    if pid is None:
        raise ValueError(f"no profile {name!r}")
    return pid


def load(db, pid=None):
    """{profile, settings: {key: value}, slots: {i: {model, x, y, yaw}}} of a profile (the active one by default)."""
    if pid is None:
        pid, name = active(db)
    else:
        name = db.val("SELECT name FROM profile WHERE id = %s", (pid,))
    settings = dict(db.all("SELECT key, value FROM setting_value WHERE profile_id = %s ORDER BY key", (pid,)))
    slots = {r[0]: {"model": r[1], "x": r[2], "y": r[3], "yaw": r[4]} for r in
             db.all("SELECT slot, model, x, y, yaw_deg FROM robot_slot WHERE profile_id = %s ORDER BY slot", (pid,))}
    return {"profile_id": pid, "profile": name, "settings": settings, "slots": slots}


def default_cfg():
    return {"profile_id": None, "profile": None, "settings": {}, "slots": {}}


def effective(cfg, key):
    v = cfg["settings"].get(key)
    if v is None and key in cat.BY_KEY:
        v = cat.BY_KEY[key]["default"]
    return v


def num_robots(cfg):
    try:
        return int(effective(cfg, "NUM_ROBOTS") or 0)
    except ValueError:
        return 0


def problems(cfg):
    """(errors, warnings): errors stop render (compose would fail or the sim reject the spawn)."""
    errors, warnings = [], []
    n = num_robots(cfg)
    if not 0 <= n <= cat.MAX_SLOTS:
        errors.append(f"NUM_ROBOTS={n}: 0-{cat.MAX_SLOTS}")
        n = 0
    seen = {}
    for i in range(n):
        model = cfg["slots"].get(i, {}).get("model", GENERIC_SLOT_MODEL)
        ns = slot_ns(model, i)
        if ns in seen:
            errors.append(f"slots {seen[ns]} and {i} are both {ns}: one real robot can only be in one slot")
        seen[ns] = i
        if "_" in model and not (ROOT / "robot_data" / model / "robot.yaml").exists():
            warnings.append(f"slot {i} ({model}): no robot_data/{model}/robot.yaml, its container exits at once")
        if not (ROOT / "sim/assets" / model / f"{model}.urdf").exists():
            warnings.append(f"slot {i}: no sim model sim/assets/{model}/ (scripts/gen_urdf.sh)")
    for k, v in cfg["settings"].items():
        err = cat.check_value(k, v)
        if err:
            errors.append(f"{k}={v}: must be {err}")
    return errors, warnings


def _env_value(v):
    return f'"{v}"' if re.search(r"[\s#]", v) else v


def render_text(cfg, source):
    """The .env text for a profile: its settings (unset ones are left to compose's defaults) and the slots.
    No timestamp: the same settings give the same text, so .env is only rewritten when they change."""
    lines = [f"{HEADER} from {source} -- do not edit: changes are overwritten.",
             "# Change settings in the web UI (tools/sim_ui, Configuration) or with scripts/fleetcfg.py set KEY=VALUE.",
             f"# Profile: {cfg['profile'] or '(none: database unreachable, defaults)'}."]
    settings = dict(cfg["settings"])
    settings.setdefault("NUM_ROBOTS", cat.BY_KEY["NUM_ROBOTS"]["default"])
    for section in cat.SECTIONS:
        keys = [s["key"] for s in cat.SETTINGS if s["section"] == section and s["key"] in settings]
        if keys:
            lines += ["", f"# {section}"] + [f"{k}={_env_value(settings[k])}" for k in keys]
    other = sorted(k for k in settings if k not in cat.BY_KEY)
    if other:
        lines += ["", "# Not in scripts/fleet_settings.py"] + [f"{k}={_env_value(settings[k])}" for k in other]
    n = num_robots(cfg)
    lines += ["", "# Robot slots: compose profile n<NUM_ROBOTS> starts slots 0..N-1; container name, hostname",
              "# and namespace follow each slot's model (see docker-compose.yml)", f"COMPOSE_PROFILES=n{n}"]
    for i in range(cat.MAX_SLOTS):
        s = cfg["slots"].get(i)
        model = s["model"] if s else GENERIC_SLOT_MODEL
        if s:
            lines.append(f"ROBOT_MODEL_{i}={model}")
            if s.get("x") is not None:
                lines.append(f"ROBOT_POSE_{i}={s['x']:g},{s['y']:g},{s['yaw']:g}")
        if "_" in model:
            lines.append(f"ROBOT_SUFFIX_{i}=")
        lines.append(f"ROBOT_HOSTNAME_{i}=cpr-{slot_ns(model, i).replace('_', '-')}")
    return "\n".join(lines) + "\n"


def _real_rows(db):
    return db.dicts("SELECT id, host, ssh_user AS user, cutter FROM real_robot ORDER BY id")


def _write_real_file(rows):
    data = {r["id"]: {"host": r["host"], **({"user": r["user"]} if r["user"] != "robot" else {}),
                      "cutter": r["cutter"]} for r in rows}
    write_if_changed(REAL_FILE, json.dumps(data, indent=2) + "\n")


def render(actor=None, db=None):
    """Write .env (and the offline real-robot list) from the active profile. Returns {source, profile, changed,
    errors, warnings, why}: source "database", or "offline" (database unreachable: .env kept, or made from the
    defaults if there is none). Errors: nothing written."""
    try:
        if db is None:
            with DB(actor) as own:
                return render(actor, own)
        cfg = load(db)
        real = _real_rows(db)
    except Unavailable as e:
        r = {"source": "offline", "why": str(e), "profile": None, "errors": [], "warnings": [], "changed": False}
        if not ENV_FILE.exists():
            r["changed"] = write_if_changed(ENV_FILE, render_text(default_cfg(), "the defaults (no database)"))
        return r
    errors, warnings = problems(cfg)
    r = {"source": "database", "why": "", "profile": cfg["profile"], "errors": errors, "warnings": warnings,
         "changed": False}
    if not errors:
        r["changed"] = write_if_changed(ENV_FILE, render_text(cfg, f"database {DB_NAME}"))
        _write_real_file(real)
    return r


LAST_RENDER = {}  # env()'s last render(): where .env came from (the web UI's header shows it)


def env(actor=None):
    """The variables compose sees: .env rendered fresh from the database when it is reachable, else as it is."""
    global LAST_RENDER
    LAST_RENDER = render(actor)  # rebound, not updated in place: other threads read it
    return read_env_file()


# ---------------------------------------------------------------- changes

def set_settings(updates, actor=None):
    """{key: value or None (= back to the default)} into the active profile, then render. Values already in effect
    are skipped, so a caller that rewrites unchanged values works while the database is down."""
    for k, v in updates.items():
        if not re.fullmatch(r"[A-Z][A-Z0-9_]*", k) or cat.is_derived(k):
            raise ValueError(f"{k}: not a setting (robot slots: scripts/fleetcfg.py slot / robots)")
        if v is not None:
            err = cat.check_value(k, str(v))
            if err:
                raise ValueError(f"{k} must be {err}")
    current = read_env_file()
    unchanged = all(v is not None and (current[k] if k in current else cat.BY_KEY.get(k, {}).get("default")) == str(v)
                    for k, v in updates.items())
    try:
        with DB(actor) as db:
            pid, _ = active(db)
            for k, v in updates.items():
                if v is None:
                    db.q("DELETE FROM setting_value WHERE profile_id = %s AND key = %s", (pid, k))
                else:
                    db.q("INSERT INTO setting_value (profile_id, key, value) VALUES (%s, %s, %s) ON CONFLICT "
                         "(profile_id, key) DO UPDATE SET value = EXCLUDED.value", (pid, k, str(v)))
            r = render(actor, db)
            if r["errors"]:
                raise ValueError("; ".join(r["errors"]))
            return r
    except Unavailable as e:
        if unchanged:  # nothing to change: .env already says so
            return {"source": "offline", "why": str(e), "changed": False, "errors": [], "warnings": []}
        raise


def _pose(p):
    if p is None:
        return None, None, None
    vals = [float(p.get(k)) for k in ("x", "y", "yaw")]
    if not all(math.isfinite(v) for v in vals):
        raise ValueError("pose values must be finite numbers")
    return tuple(vals)


def set_slots(robots, actor=None, num_robots=None):
    """Slots 0..len-1 from [{model, x?, y?, yaw?} or None (= forget the slot)], a pose with all three or none;
    rows of higher slots are kept. NUM_ROBOTS too if given. Then render. While the database can't be reached, a
    request that changes no model and no NUM_ROBOTS passes (a spawn hands its poses to the sim itself)."""
    if len(robots) > cat.MAX_SLOTS:
        raise ValueError(f"at most {cat.MAX_SLOTS} robots")
    if num_robots is not None and not 0 <= int(num_robots) <= cat.MAX_SLOTS:
        raise ValueError(f"NUM_ROBOTS 0-{cat.MAX_SLOTS}")
    rows = []
    for i, r in enumerate(robots):
        if r is None:
            rows.append(None)
            continue
        model = r.get("model") or GENERIC_SLOT_MODEL
        if not re.fullmatch(r"[a-z0-9]+(_[0-9]+)?", model):
            raise ValueError(f"slot {i}: {model!r} is not a model id")
        has_pose = all(r.get(k) not in (None, "") for k in ("x", "y", "yaw"))
        rows.append((model, *_pose(r if has_pose else None)))
    current = read_env_file()
    unchanged = (num_robots is None or current.get("NUM_ROBOTS") == str(num_robots)) and all(
        row is not None and current.get(f"ROBOT_MODEL_{i}") == row[0] for i, row in enumerate(rows))
    try:
        with DB(actor) as db:
            pid, _ = active(db)
            for i, row in enumerate(rows):
                if row is None:
                    db.q("DELETE FROM robot_slot WHERE profile_id = %s AND slot = %s", (pid, i))
                    continue
                db.q("INSERT INTO robot_slot (profile_id, slot, model, x, y, yaw_deg) VALUES (%s, %s, %s, %s, %s, "
                     "%s) ON CONFLICT (profile_id, slot) DO UPDATE SET model = EXCLUDED.model, x = EXCLUDED.x, "
                     "y = EXCLUDED.y, yaw_deg = EXCLUDED.yaw_deg", (pid, i, *row))
            if num_robots is not None:
                db.q("INSERT INTO setting_value (profile_id, key, value) VALUES (%s, 'NUM_ROBOTS', %s) ON CONFLICT "
                     "(profile_id, key) DO UPDATE SET value = EXCLUDED.value", (pid, str(int(num_robots))))
            r = render(actor, db)
            if r["errors"]:
                raise ValueError("; ".join(r["errors"]))
            return r
    except Unavailable as e:
        if unchanged:
            return {"source": "offline", "why": str(e), "changed": False, "errors": [], "warnings": []}
        raise


def set_slot(i, model=None, pose=None, clear_pose=False, remove=False, actor=None):
    if not 0 <= i < cat.MAX_SLOTS:
        raise ValueError(f"slot 0-{cat.MAX_SLOTS - 1}")
    with DB(actor) as db:
        pid, _ = active(db)
        if remove:
            db.q("DELETE FROM robot_slot WHERE profile_id = %s AND slot = %s", (pid, i))
        else:
            cur = load(db, pid)["slots"].get(i, {"model": GENERIC_SLOT_MODEL, "x": None, "y": None, "yaw": None})
            model = model or cur["model"]
            if not re.fullmatch(r"[a-z0-9]+(_[0-9]+)?", model):
                raise ValueError(f"{model!r} is not a model id")
            x, y, yaw = (None, None, None) if clear_pose else _pose(pose) if pose else (cur["x"], cur["y"], cur["yaw"])
            db.q("INSERT INTO robot_slot (profile_id, slot, model, x, y, yaw_deg) VALUES (%s, %s, %s, %s, %s, %s) "
                 "ON CONFLICT (profile_id, slot) DO UPDATE SET model = EXCLUDED.model, x = EXCLUDED.x, "
                 "y = EXCLUDED.y, yaw_deg = EXCLUDED.yaw_deg", (pid, i, model, x, y, yaw))
        r = render(actor, db)
        if r["errors"]:
            raise ValueError("; ".join(r["errors"]))
        return r


