#!/usr/bin/env python3
"""The fleet's settings, kept in the base station's fleet_config database; .env is generated from them.

  scripts/fleetcfg.py show                          the active profile: settings, robot slots, problems
  scripts/fleetcfg.py get KEY                       a setting's value (its default if the profile doesn't set it)
  scripts/fleetcfg.py set KEY=VALUE ...             change settings (and render .env); `unset KEY ...` = default
  scripts/fleetcfg.py robots N                      NUM_ROBOTS
  scripts/fleetcfg.py slot I MODEL [--pose X,Y,YAW | --no-pose]   slot I's model and spawn pose; `slot I --remove`
  scripts/fleetcfg.py render                        write .env (and the real-robot list) from the database
  scripts/fleetcfg.py profile list | use NAME | new NAME [--from P] | rename OLD NEW | delete NAME
                              | notes NAME TEXT | export [NAME] | import FILE [--name NAME]
  scripts/fleetcfg.py history [-n N] | revert ID    the change log (who changed what, when); undo one change
  scripts/fleetcfg.py runs [-n N]                   sim starts and spawns (scripts/fleet.sh) and what they ran with
  scripts/fleetcfg.py real list | set ID [--host H] [--user U] [--cutter | --no-cutter] | remove ID
  scripts/fleetcfg.py import-env FILE [--profile NAME]   load an old-style .env into a profile
  scripts/fleetcfg.py init                          create the database in a running base station (normally
                                                    basestation/entrypoint.sh does it at start)
  scripts/fleetcfg.py check                         the catalog's defaults vs. docker-compose.yml's

What each setting means is scripts/fleet_settings.py. The database is reached like status_server does: the base
station's PostgreSQL on 127.0.0.1:5433 (BASESTATION_PG_PORT), user admin, PGPASSWORD from db.env; FLEET_DB_HOST /
FLEET_DB_PORT / FLEET_DB_USER / FLEET_CONFIG_DB override. If it can't be reached, .env stays as last rendered (the
fleet still starts) and only changes are refused. The first use imports the existing .env (or the last one
committed to git) and tools/sim_ui/real_robots.json into a profile "default".
Needs psycopg (3) or psycopg2; tools/sim_ui/server.py imports this module.
"""
